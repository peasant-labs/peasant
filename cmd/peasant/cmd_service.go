// serviceUnits is one rendered unit pair.
type serviceUnits struct {
	Service string
	Timer   string
}

// serviceSchedule is the validated timer schedule: exactly one of interval
// or calendar is set.
type serviceSchedule struct {
	interval        time.Duration
	calendar        string
	randomizedDelay time.Duration
}

func newServiceSchedule(flags serviceInstallFlags, intervalSet bool) (serviceSchedule, error) {
	if flags.onCalendar != "" && intervalSet {
		return serviceSchedule{}, errors.New("--interval and --on-calendar are mutually exclusive")
	}
	if flags.randomizedDelay < 0 {
		return serviceSchedule{}, fmt.Errorf("--randomized-delay must not be negative (got %s)", flags.randomizedDelay)
	}
	if flags.onCalendar != "" {
		if strings.TrimSpace(flags.onCalendar) == "" || strings.ContainsFunc(flags.onCalendar, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
			return serviceSchedule{}, fmt.Errorf("--on-calendar %q must be one line of text", flags.onCalendar)
		}
		return serviceSchedule{calendar: strings.TrimSpace(flags.onCalendar), randomizedDelay: flags.randomizedDelay}, nil
	}
	if flags.interval < minServiceInterval {
		return serviceSchedule{}, fmt.Errorf("--interval must be at least %s (got %s)", systemdTimespan(minServiceInterval), flags.interval)
	}
	return serviceSchedule{interval: flags.interval, randomizedDelay: flags.randomizedDelay}, nil
}

// serviceEnv is one Environment= assignment in the service unit.
type serviceEnv struct {
	Name  string `yaml:"name"`
	Value string `yaml:"value"`
}

// serviceInvocation is what the service runs, in order: the harvest command
// line (binary first), then the redact command line, with one environment.
//
// Harvest stores transcripts as recorded (see ingest.WithRedactor: no
// production ingest redacts content). The second step is the existing
// `peasant redact --all`, which redacts the peasant-sync copies in place at
// the configured level with the peasant-labs/redact rules and skips the
// sessions already current. It runs as ExecStopPost=, so it runs after a
// failed harvest too. A redact == nil invocation renders harvest only.
type serviceInvocation struct {
	harvest []string
	redact  []string
	env     []serviceEnv
}

// renderServiceUnits renders the unit pair for the invocation and schedule.
// It is pure so the YAML fixture can pin it.
func renderServiceUnits(invocation serviceInvocation, schedule serviceSchedule) serviceUnits {
	var svc strings.Builder
	svc.WriteString(serviceUnitMarker + "\n")
	svc.WriteString("[Unit]\n")
	svc.WriteString("Description=Peasant: harvest AI coding agent transcripts, then redact the local copies\n\n")
	svc.WriteString("[Service]\n")
	svc.WriteString("Type=oneshot\n")
	for _, env := range invocation.env {
		svc.WriteString("Environment=" + systemdQuote(env.Name+"="+env.Value, false) + "\n")
	}
	svc.WriteString("ExecStart=" + systemdExecLine(invocation.harvest) + "\n")
	if invocation.redact != nil {
		// ExecStopPost= runs after ExecStart= whether it succeeded or not,
		// so one failing session (harvest exits 1) cannot keep the copies
		// harvest did write unredacted. The unit fails when either step
		// fails; systemd keeps the first failure, so when both fail only
		// the journal shows redact's.
		svc.WriteString("ExecStopPost=" + systemdExecLine(invocation.redact) + "\n")
		// TimeoutStopSec= bounds only the stop-post phase, that is redact
		// (a oneshot's ExecStart= has no default limit). 90s by default, too
		// short for a first redact over a large store. A run killed at the
		// limit leaves whole files (redact writes by rename) and the next
		// run continues where it stopped.
		svc.WriteString("TimeoutStopSec=30min\n")
	}
	svc.WriteString("Nice=10\n")
	svc.WriteString("IOSchedulingClass=idle\n")

	var tmr strings.Builder
	tmr.WriteString(serviceUnitMarker + "\n")
	tmr.WriteString("[Unit]\n")
	tmr.WriteString("Description=Peasant: run " + serviceUnitName + " on a schedule\n\n")
	tmr.WriteString("[Timer]\n")
	if schedule.calendar != "" {
		tmr.WriteString("OnCalendar=" + schedule.calendar + "\n")
		// Persistent= applies to OnCalendar= only: a run missed while the
		// machine was off or asleep starts at the next boot or login.
		tmr.WriteString("Persistent=true\n")
	} else {
		tmr.WriteString("OnStartupSec=" + systemdTimespan(serviceStartupDelay) + "\n")
		tmr.WriteString("OnUnitActiveSec=" + systemdTimespan(schedule.interval) + "\n")
	}
	if schedule.randomizedDelay > 0 {
		tmr.WriteString("RandomizedDelaySec=" + systemdTimespan(schedule.randomizedDelay) + "\n")
	}
	tmr.WriteString("Unit=" + serviceUnitName + "\n\n")
	tmr.WriteString("[Install]\n")
	tmr.WriteString("WantedBy=timers.target\n")
	return serviceUnits{Service: svc.String(), Timer: tmr.String()}
}

// systemdTimespan renders d in systemd's time span syntax ("1h 30min"),
// whole seconds only.
func systemdTimespan(d time.Duration) string {
	d = d.Round(time.Second)
	if d <= 0 {
		return "0"
	}
	var parts []string
	for _, unit := range []struct {
		size time.Duration
		name string
	}{{24 * time.Hour, "d"}, {time.Hour, "h"}, {time.Minute, "min"}, {time.Second, "s"}} {
		if n := d / unit.size; n > 0 {
			parts = append(parts, fmt.Sprintf("%d%s", n, unit.name))
			d -= n * unit.size
		}
	}
	return strings.Join(parts, " ")
}

// systemdExecLine quotes every argument for ExecStart=. systemd splits the
// line itself (no shell): inside double quotes it unescapes \\ and \", and
// it expands % specifiers and $ variables, which %% and $$ keep literal.
func systemdExecLine(args []string) string {
	quoted := make([]string, len(args))
	for i, arg := range args {
		quoted[i] = systemdQuote(arg, true)
	}
	return strings.Join(quoted, " ")
}

// systemdQuote double-quotes one word. Every setting expands % specifiers;
// only ExecStart= expands $ variables, so only it doubles $.
func systemdQuote(word string, execLine bool) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range word {
		switch {
		case r == '\\' || r == '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '%':
			b.WriteString("%%")
		case r == '$' && execLine:
			b.WriteString("$$")
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// serviceHarvestInvocation is what the service runs: the binary, then
// `harvest` with every directory resolved to an absolute path now, because
// the user manager inherits neither the shell's XDG_* variables nor this
// invocation's flags. The same homes are also set as XDG_* in the unit's
// environment, so every path harvest derives from the environment rather
// than a flag (the default peasant-sync output under the data home, the
// redaction rules' XDG paths) resolves to what this command resolved.
func serviceHarvestInvocation(cmd *cobra.Command, deps serviceDeps, flags serviceInstallFlags) (serviceInvocation, error) {
	exe, global, homes, err := serviceGlobalArgs(cmd, deps)
	if err != nil {
		return serviceInvocation{}, err
	}
	harvest := append([]string{exe, "harvest"}, global...)
	if flags.sourceHarness != "" || flags.sourcePath != "" {
		if flags.sourceHarness == "" {
			return serviceInvocation{}, errors.New("--source-path requires --source-harness")
		}
		if flags.sourcePath == "" {
			return serviceInvocation{}, errors.New("--source-harness requires --source-path")
		}
		harness, err := resolveHarnessFlag(flags.sourceHarness)
		if err != nil {
			return serviceInvocation{}, err
		}
		resolved, err := ingest.NewResolvedPath(flags.sourcePath)
		if err != nil {
			return serviceInvocation{}, fmt.Errorf("resolve --source-path: %w", err)
		}
		harvest = append(harvest, "--source-harness", string(harness), "--source-path", string(resolved))
	}
	invocation := serviceInvocation{harvest: harvest}
	if !flags.noRedact {
		invocation.redact = append(append([]string{exe, "redact"}, global...), "--all")
	}
	invocation.env = []serviceEnv{
		{Name: defaults.EnvXDGDataHome.String(), Value: homes.data},
		{Name: defaults.EnvXDGConfigHome.String(), Value: homes.config},
		{Name: defaults.EnvXDGStateHome.String(), Value: homes.state},
	}
	return invocation, nil
}

type serviceHomes struct{ data, config, state string }

// serviceExecutable is the binary path the unit runs. os.Executable is the
// resolved file (/proc/self/exe), which for a package-manager install is a
// versioned path (/nix/store/<hash>-peasant-…/bin/peasant, a Homebrew Cellar
// version directory) that an upgrade and garbage collection remove. When
// `peasant` on PATH is a link to this same file, the unit runs that PATH
// entry instead, which the package manager repoints on upgrade.
func serviceExecutable(deps serviceDeps) (string, error) {
	exe, err := deps.executable()
	if err != nil {
		return "", err
	}
	if exe, err = filepath.Abs(exe); err != nil {
		return "", err
	}
	if deps.lookPath == nil {
		return exe, nil
	}
	onPath, err := deps.lookPath(string(defaults.AppName))
	if err != nil {
		return exe, nil
	}
	onPath, err = filepath.Abs(onPath)
	if err != nil {
		return exe, nil
	}
	resolved, err := filepath.EvalSymlinks(onPath)
	if err != nil {
		return exe, nil
	}
	exeResolved, err := filepath.EvalSymlinks(exe)
	if err != nil || resolved != exeResolved {
		return exe, nil
	}
	return onPath, nil
}

// serviceGlobalArgs resolves the binary and the root directory flags every
// step of the unit passes.
func serviceGlobalArgs(cmd *cobra.Command, deps serviceDeps) (string, []string, serviceHomes, error) {
	fail := func(what string, err error) (string, []string, serviceHomes, error) {
		return "", nil, serviceHomes{}, fmt.Errorf("resolve %s: %w", what, err)
	}
	exe, err := serviceExecutable(deps)
	if err != nil {
		return fail("the peasant binary", err)
	}
	home := func(p string) (string, error) { return filepath.Abs(filepath.Dir(p)) }
	var homes serviceHomes
	if homes.data, err = home(string(defaults.ResolveDataDirPathWith(dataDirOverride(cmd)))); err != nil {
		return fail("the data directory", err)
	}
	if homes.config, err = home(string(defaults.ResolveConfigDirPathWith(configDirOverride(cmd)))); err != nil {
		return fail("the config directory", err)
	}
	if homes.state, err = home(string(defaults.ResolveStateDirPathWith(stateDirOverride(cmd)))); err != nil {
		return fail("the state directory", err)
	}
	global := []string{"--data-dir", homes.data, "--config-dir", homes.config, "--state-dir", homes.state}
	if f := commandFlag(cmd, "config"); f != nil && f.Changed {
		configPath, err := filepath.Abs(f.Value.String())
		if err != nil {
			return fail("--config", err)
		}
		global = append(global, "--config", configPath)
	}
	return exe, global, homes, nil
}

// validateUnitWords refuses what systemd cannot run or what would change the
// unit's structure: a control character (a newline would start a new
// directive) in any word, and in the executable path the characters systemd
// rejects there however they are quoted (", \, ') or does not unescape ($).
func validateUnitWords(invocation serviceInvocation) error {
	isControl := func(r rune) bool { return r < 0x20 || r == 0x7f }
	words := append(append([]string{}, invocation.harvest...), invocation.redact...)
	for _, env := range invocation.env {
		words = append(words, env.Value)
	}
	for _, word := range words {
		if strings.ContainsFunc(word, isControl) {
			return fmt.Errorf("cannot write a systemd unit for the path %q: it contains a control character (such as a newline); use a path without one", word)
		}
	}
	if exe := invocation.harvest[0]; strings.ContainsAny(exe, "\"\\'$") {
		return fmt.Errorf("cannot write a systemd unit for the peasant binary %q: systemd cannot run an executable whose path contains \", \\, ' or $; install or link peasant at a path without them and run that one", exe)
	}
	return nil
}

func requireSystemdHost(deps serviceDeps) error {
	if deps.goos != "linux" {
		return fmt.Errorf("peasant service manages systemd user units and runs on Linux only (this is %s); schedule 'peasant harvest' with your platform's scheduler instead", deps.goos)
	}
	return nil
}

// requireUserManager checks that `systemctl --user` reaches a running user
// manager before anything is changed.
func requireUserManager(ctx context.Context, deps serviceDeps) error {
	out, err := deps.systemctl(ctx, "show-environment")
	if err == nil {
		return nil
	}
	if errors.Is(err, errSystemctlMissing) {
		return errors.New("systemctl not found on PATH: peasant service needs systemd. Use --dry-run to print the units, or schedule 'peasant harvest' with cron")
	}
	return fmt.Errorf("cannot reach the systemd user manager (systemctl --user: %s). "+
		"Run this from a login session, or check that XDG_RUNTIME_DIR is set (usually /run/user/$(id -u)); "+
		"for a timer that runs while you are logged out, run 'loginctl enable-linger'. Use --dry-run to print the units", firstLine(out, err))
}

func firstLine(out string, err error) string {
	if line, _, _ := strings.Cut(strings.TrimSpace(out), "\n"); line != "" {
		return line
	}
	return err.Error()
}

// unitFileState is what is at a unit path.
type unitFileState int

const (
	unitFileAbsent unitFileState = iota
	unitFileOurs
	unitFileForeign
)

func (s unitFileState) String() string {
	switch s {
	case unitFileOurs:
		return "installed"
	case unitFileForeign:
		return "present, not written by peasant (left alone)"
	default:
		return "not installed"
	}
}

func readUnitFileState(path string) (unitFileState, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return unitFileAbsent, nil
	}
	if err != nil {
		return unitFileAbsent, fmt.Errorf("read %s: %w", path, err)
	}
	if bytes.HasPrefix(data, []byte(serviceUnitMarker+"\n")) {
		return unitFileOurs, nil
	}
	return unitFileForeign, nil
}

func runServiceInstall(cmd *cobra.Command, deps serviceDeps, flags serviceInstallFlags, intervalSet bool) error {
	ctx := cmd.Context()
	out := cmd.OutOrStdout()
	if err := requireSystemdHost(deps); err != nil {
		return err
	}
	schedule, err := newServiceSchedule(flags, intervalSet)
	if err != nil {
		return err
	}
	invocation, err := serviceHarvestInvocation(cmd, deps, flags)
	if err != nil {
		return err
	}
	if err := validateUnitWords(invocation); err != nil {
		return err
	}
	// Refuse now what every scheduled run would refuse: a stored redaction
	// level this version will not ingest at.
	configPath := resolveConfigPath(cmd)
	cfg, err := loadRunConfig(configPath, true)
	if err != nil {
		return fmt.Errorf("load config: %w", err)
	}
	if err := checkIngestRedactionLevel(cfg, configPath, "peasant service install"); err != nil {
		return err
	}
	unitDir, err := deps.unitDir()
	if err != nil {
		return err
	}
	units := renderServiceUnits(invocation, schedule)
	files := []struct{ name, text string }{{serviceUnitName, units.Service}, {timerUnitName, units.Timer}}

	if flags.dryRun {
		for _, f := range files {
			fmt.Fprintf(out, "# %s\n%s\n", filepath.Join(unitDir, f.name), f.text)
		}
		fmt.Fprintln(out, "# would run: systemctl --user daemon-reload")
		fmt.Fprintf(out, "# would run: systemctl --user enable %s\n", timerUnitName)
		fmt.Fprintf(out, "# would run: systemctl --user restart %s\n", timerUnitName)
		return nil
	}
	if err := requireUserManager(ctx, deps); err != nil {
		return err
	}
	for _, f := range files {
		path := filepath.Join(unitDir, f.name)
		state, err := readUnitFileState(path)
		if err != nil {
			return err
		}
		if state == unitFileForeign {
			return fmt.Errorf("%s exists and was not written by peasant; move it aside or remove it, then re-run peasant service install", path)
		}
	}
	if err := os.MkdirAll(unitDir, 0o755); err != nil {
		return fmt.Errorf("create %s: %w", unitDir, err)
	}
	for _, f := range files {
		path := filepath.Join(unitDir, f.name)
		if err := writeUnitFileAtomic(path, []byte(f.text)); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
		fmt.Fprintf(out, "wrote %s\n", path)
	}
	if err := systemctlStep(ctx, deps, out, "daemon-reload"); err != nil {
		return err
	}
	// enable arms the timer at boot; restart applies a changed schedule to a
	// timer that is already running (enable --now leaves it as it was).
	if err := systemctlStep(ctx, deps, out, "enable", timerUnitName); err != nil {
		return err
	}
	if err := systemctlStep(ctx, deps, out, "restart", timerUnitName); err != nil {
		return err
	}
	fmt.Fprintf(out, "enabled %s (%s)\n", timerUnitName, describeSchedule(schedule))
	fmt.Fprintf(out, "logs: journalctl --user -u %s\n", serviceUnitName)
	return nil
}

func describeSchedule(s serviceSchedule) string {
	what := "every " + systemdTimespan(s.interval)
	if s.calendar != "" {
		what = "on calendar " + s.calendar
	}
	if s.randomizedDelay > 0 {
		what += ", randomized delay " + systemdTimespan(s.randomizedDelay)
	}
	return what
}

func systemctlStep(ctx context.Context, deps serviceDeps, out io.Writer, args ...string) error {
	if text, err := deps.systemctl(ctx, args...); err != nil {
		return fmt.Errorf("systemctl --user %s: %s", strings.Join(args, " "), firstLine(text, err))
	}
	fmt.Fprintf(out, "ran systemctl --user %s\n", strings.Join(args, " "))
	return nil
}

// writeUnitFileAtomic writes a unit through a same-directory temp file and a
// rename, so systemd never reads a half-written unit.
func writeUnitFileAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".peasant-unit-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmpName, serviceUnitPerm); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

func runServiceStatus(cmd *cobra.Command, deps serviceDeps) error {
	ctx := cmd.Context()
	out := cmd.OutOrStdout()
	if err := requireSystemdHost(deps); err != nil {
		return err
	}
	unitDir, err := deps.unitDir()
	if err != nil {
		return err
	}
	for _, name := range []string{serviceUnitName, timerUnitName} {
		path := filepath.Join(unitDir, name)
		state, err := readUnitFileState(path)
		if err != nil {
			return err
		}
		fmt.Fprintf(out, "%s: %s\n", path, state)
	}
	if err := requireUserManager(ctx, deps); err != nil {
		return err
	}
	// is-enabled and is-active exit non-zero for "disabled" and "inactive";
	// their one-word answer is the status, not a failure.
	for _, query := range []string{"is-enabled", "is-active"} {
		text, err := deps.systemctl(ctx, query, timerUnitName)
		answer := strings.TrimSpace(text)
		if answer == "" && err != nil {
			answer = err.Error()
		}
		fmt.Fprintf(out, "%s %s: %s\n", timerUnitName, query, answer)
	}
	if text, err := deps.systemctl(ctx, "list-timers", "--all", "--no-pager", timerUnitName); err == nil {
		fmt.Fprint(out, text)
	}
	fmt.Fprintf(out, "logs: journalctl --user -u %s\n", serviceUnitName)
	return nil
}

func runServiceUninstall(cmd *cobra.Command, deps serviceDeps, dryRun bool) error {
	ctx := cmd.Context()
	out := cmd.OutOrStdout()
	if err := requireSystemdHost(deps); err != nil {
		return err
	}
	unitDir, err := deps.unitDir()
	if err != nil {
		return err
	}
	var ours []string
	timerOurs := false
	for _, name := range []string{timerUnitName, serviceUnitName} {
		path := filepath.Join(unitDir, name)
		state, err := readUnitFileState(path)
		if err != nil {
			return err
		}
		switch state {
		case unitFileOurs:
			ours = append(ours, path)
			timerOurs = timerOurs || name == timerUnitName
		case unitFileForeign:
			fmt.Fprintf(out, "left %s: not written by peasant\n", path)
		}
	}
	if len(ours) == 0 {
		fmt.Fprintln(out, "nothing to uninstall: no peasant-generated units in "+unitDir)
		return nil
	}
	if dryRun {
		if timerOurs {
			fmt.Fprintf(out, "would run: systemctl --user disable --now %s\n", timerUnitName)
		}
		for _, path := range ours {
			fmt.Fprintf(out, "would remove %s\n", path)
		}
		fmt.Fprintln(out, "would run: systemctl --user daemon-reload")
		return nil
	}
	if err := requireUserManager(ctx, deps); err != nil {
		return err
	}
	if timerOurs {
		if err := systemctlStep(ctx, deps, out, "disable", "--now", timerUnitName); err != nil {
			return err
		}
	}
	for _, path := range ours {
		if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("remove %s: %w", path, err)
		}
		fmt.Fprintf(out, "removed %s\n", path)
	}
	return systemctlStep(ctx, deps, out, "daemon-reload")
}
