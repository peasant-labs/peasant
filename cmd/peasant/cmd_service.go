// The systemd user units `peasant service install` manages.
const (
	serviceUnitName = "peasant-harvest.service"
	timerUnitName   = "peasant-harvest.timer"
	// serviceUnitMarker is the first line of every generated unit. Uninstall
	// and a re-install touch only files that start with it, so a unit the
	// user wrote by hand under the same name is never overwritten or deleted.
	serviceUnitMarker = "# Generated by peasant service install. Re-run it to change this unit; peasant service uninstall removes it."
	// serviceUnitPerm is what systemd expects for a user unit file. A unit
	// carries no credentials: only the binary, directory paths, and flags.
	serviceUnitPerm os.FileMode = 0o644

	defaultServiceInterval        = time.Hour
	defaultServiceRandomizedDelay = 5 * time.Minute
	minServiceInterval            = time.Minute
	// serviceStartupDelay delays the first run after the user manager starts
	// (login), and makes a freshly enabled timer fire right away: systemd
	// elapses an OnStartupSec= that is already in the past immediately.
	serviceStartupDelay = 2 * time.Minute
)

// systemctlRunner runs `systemctl --user <args>` and returns its combined
// output. Tests inject a fake; production runs the real binary.
type systemctlRunner func(ctx context.Context, args ...string) (string, error)

// serviceDeps are the host facts `peasant service` depends on. Production
// wiring reads the real host; tests replace every field so no test reaches
// the real systemd, HOME, or unit directory.
type serviceDeps struct {
	goos       string
	executable func() (string, error)
	// lookPath resolves a command name on PATH (exec.LookPath).
	lookPath  func(string) (string, error)
	unitDir   func() (string, error)
	systemctl systemctlRunner
}

func productionServiceDeps() serviceDeps {
	return serviceDeps{
		goos:       runtime.GOOS,
		executable: os.Executable,
		lookPath:   exec.LookPath,
		unitDir:    defaultSystemdUserUnitDir,
		systemctl:  runSystemctlUser,
	}
}

// defaultSystemdUserUnitDir is the per-user unit directory systemd reads:
// $XDG_CONFIG_HOME/systemd/user, else ~/.config/systemd/user.
func defaultSystemdUserUnitDir() (string, error) {
	if configHome := os.Getenv(defaults.EnvXDGConfigHome.String()); configHome != "" {
		return filepath.Join(configHome, "systemd", "user"), nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("resolve the systemd user unit directory: %w", err)
	}
	return filepath.Join(home, ".config", "systemd", "user"), nil
}

func runSystemctlUser(ctx context.Context, args ...string) (string, error) {
	path, err := exec.LookPath("systemctl")
	if err != nil {
		return "", errSystemctlMissing
	}
	out, err := exec.CommandContext(ctx, path, append([]string{"--user"}, args...)...).CombinedOutput()
	return string(out), err
}

