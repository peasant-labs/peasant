// redaction fixture (schema.RedactionsYAML). The fixture is the single source of
// truth for redaction example DATA; this package owns only the UI presentation
// concern the contract leaf deliberately does NOT carry:
//
//   - contextBefore/contextAfter code snippets, kept in a side-table keyed by
//     case Name and merged at codegen.
//
// Category labels use the public redaction module's canonical CategoryString representation.
//
// A peasant freshness test asserts the committed mock-redactions.ts is
// byte-identical to GenerateMockRedactionsTS(), so the TS mock cannot drift from
// the contract fixture. Regenerate with `go run ./cmd/gen-mock-redactions`.
