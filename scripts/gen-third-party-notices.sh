#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES: the license texts of every third-party Go module
# compiled into the peasant binary.
#
# WHY: `go build` produces a static binary that keeps none of its dependencies'
# license files. peasant ships that binary through Homebrew, deb, and rpm. The
# permissive licenses of those dependencies (MIT / BSD / ISC / Apache-2.0) all
# require their copyright and permission notices to travel with a binary
# redistribution. This script reproduces those notices in one file.
#
# HOW: it enumerates the modules actually linked into ./cmd/peasant across every
# platform .goreleaser.yml ships, finds each module's license file in the Go
# module cache, and concatenates them in a stable order. The module set is pinned
# by go.sum and the license text is content-addressed in the cache, so the output
# is byte-stable. A CI job regenerates this file and fails on any diff (see
# .github/workflows/tests.yml), so it can never drift from the deps.
#
# This reads license text straight from the cache instead of classifying license
# NAMES, because the legal obligation is on the text. A name-classifier silently
# drops modules it cannot recognize (e.g. the modernc.org SQLite stack), which is
# the one failure this file must not have. The separate copyleft guard
# (go-licenses check, in CI) owns license CLASSIFICATION.
#
# Scope: the Go modules the binary links, plus the C and C++ components the
# embedded regex engine's WebAssembly build contains. The embedded web dashboard
# (web/out) bundles npm packages whose notices are tracked as a separate
# follow-on.
#
# Requirements: run inside the Nix devShell. This uses GNU findutils (find
# -printf) and bash >= 4 (mapfile), which the devShell provides; the stock
# macOS bash 3.2 / BSD find do not have them.
#
# Usage: scripts/gen-third-party-notices.sh   (or: make third-party-notices)
set -euo pipefail
export LC_ALL=C

# Every shipped binary is built CGO_ENABLED=0 (see .goreleaser.yml builds.env
# and flake.nix). Pin it here so the enumerated module set matches the artifact
# and does not change with the presence of a C compiler on the host: with cgo
# on, the tree-sitter stack (behind a //go:build cgo seam) would be pulled in
# even though it never ships.
export CGO_ENABLED=0

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out_file="${repo_root}/THIRD_PARTY_NOTICES"
pkg="./cmd/peasant"

# The main module itself is not a third-party notice; its grant is the top-level
# LICENSE. Skip it by module path.
main_module="$(cd "${repo_root}" && go list -m 2>/dev/null | head -n1)"

# Union of linked modules across every shipped platform. A single GOOS/GOARCH
# misses platform-specific dependencies (e.g. darwin-only modules, or mousetrap,
# which only the Windows build links).
mods_tmp="$(mktemp)"
buf_tmp="$(mktemp)"
trap 'rm -f "${mods_tmp}" "${buf_tmp}"' EXIT
for pair in linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64; do
  GOOS="${pair%/*}" GOARCH="${pair#*/}" go list -deps \
    -f '{{if not .Standard}}{{if .Module}}{{.Module.Path}}@{{.Module.Version}}{{end}}{{end}}' \
    "${pkg}"
done | sort -u | grep . > "${mods_tmp}"

# Build the file in a temp buffer, then move it into place atomically.
{
  cat <<'HEADER'
THIRD-PARTY SOFTWARE NOTICES
============================

The peasant binary is a static build. It includes the third-party Go modules
listed below, plus the C and C++ components compiled into the embedded
regular-expression engine's WebAssembly build. This file reproduces their
license texts as their permissive licenses require for binary redistribution.

Do not edit this file by hand. It is generated from the module set pinned in
go.sum. To regenerate it, run: make third-party-notices

This file covers Go modules and the regex engine's statically linked components.
The embedded web dashboard bundles npm packages whose notices are tracked
separately.

HEADER

  while IFS= read -r mod; do
    path="${mod%@*}"
    [ "${path}" = "${main_module}" ] && continue

    dir="$(go list -m -f '{{.Dir}}' "${mod}" 2>/dev/null || true)"
    if [ -z "${dir}" ] || [ ! -d "${dir}" ]; then
      echo "gen-third-party-notices: no module cache dir for ${mod}" >&2
      exit 1
    fi

    # All license-like files at the module root, in a stable order. Apache
    # modules ship both LICENSE and NOTICE; both must be reproduced.
    # -iname 'LICENSE*' also matches source files such as license.go, so exclude
    # common source extensions defensively.
    mapfile -t lic_files < <(
      find "${dir}" -maxdepth 1 -type f \
        \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) \
        ! -iname '*.go' ! -iname '*.json' \
        -printf '%f\n' 2>/dev/null | sort
    )
    if [ "${#lic_files[@]}" -eq 0 ]; then
      echo "gen-third-party-notices: no license file found for ${mod} (${dir})" >&2
      exit 1
    fi

    for name in "${lic_files[@]}"; do
      printf '%s\n' "================================================================================"
      printf 'Module: %s\n' "${mod}"
      printf 'File:   %s\n' "${name}"
      printf '%s\n\n' "================================================================================"
      cat "${dir}/${name}"
      printf '\n'
    done
  done < "${mods_tmp}"

  # This audited driver is an ordinary package in the main module, so go list
  # cannot enumerate its original module license. Keep its ISC grant explicit.
  printf '%s\n' "================================================================================"
  printf 'Module: zombiezen.com/go/sqlite@v1.4.2 (audited in-module copy)\n'
  printf 'File:   LICENSE\n'
  printf '%s\n\n' "================================================================================"
  cat "${repo_root}/third_party/zombiezen-sqlite/LICENSE"
  printf '\n'

  # The regex engine embeds a statically linked WebAssembly build of RE2, so the
  # binary redistributes RE2, cre2 and Abseil even though none of them is a Go
  # module. cre2's notice travels inside the pinned module; RE2 and Abseil ship
  # no notice there, and their upstream texts are committed under
  # third_party/go-re2-engine, each filename carrying the tag it was taken from.
  engine_dir="$(go list -m -f '{{.Dir}}' github.com/wasilibs/go-re2 2>/dev/null || true)"
  engine_version="$(go list -m -f '{{.Version}}' github.com/wasilibs/go-re2 2>/dev/null || true)"
  if [ -z "${engine_dir}" ] || [ ! -f "${engine_dir}/internal/cre2/NOTICE.txt" ]; then
    echo "gen-third-party-notices: cannot read the regex engine's cre2 notice" >&2
    exit 1
  fi
  printf '%s\n' "================================================================================"
  printf 'Component: cre2 (vendored in github.com/wasilibs/go-re2@%s, compiled into its wasm blob)\n' "${engine_version}"
  printf 'File:      internal/cre2/NOTICE.txt\n'
  printf '%s\n\n' "================================================================================"
  cat "${engine_dir}/internal/cre2/NOTICE.txt"
  printf '\n'
  for notice in "${repo_root}"/third_party/go-re2-engine/*-LICENSE; do
    stem="$(basename "${notice}" -LICENSE)"
    component="${stem%%-*}"
    component_version="${stem#*-}"
    printf '%s\n' "================================================================================"
    printf 'Component: %s %s (compiled into the regex engine wasm blob)\n' "${component}" "${component_version}"
    printf 'File:      third_party/go-re2-engine/%s\n' "$(basename "${notice}")"
    printf '%s\n\n' "================================================================================"
    cat "${notice}"
    printf '\n'
  done
} > "${buf_tmp}"

mv "${buf_tmp}" "${out_file}"

count="$(grep -c '^Module: ' "${out_file}" || true)"
echo "wrote ${out_file} (${count} license entries)"
